#!/usr/bin/env bash
# gen-big.sh LANG: print a large generated source file for LANG on stdout.
# 1000 functions, each with one branch; big_run() calls the even ones with 0,
# so half the functions never run and the "x > i" arm never runs.
# Gives every emitter a large file and a long tail of uncalled functions.
set -euo pipefail
n=1000
lang=$1
case $lang in
  c)
    echo '/* Generated by gen-big.sh. Do not edit. */'
    for ((i = 0; i < n; i++)); do printf 'int f%d(int x) {\n    if (x > %d) return x - %d;\n    return %d;\n}\n' $i $i $i $i; done
    echo 'int big_run(void) {'; echo '    int s = 0;'
    for ((i = 0; i < n; i += 2)); do printf '    s += f%d(0);\n' $i; done
    echo '    return s;'; echo '}' ;;
  go)
    echo '// Code generated by gen-big.sh. DO NOT EDIT.'; echo; echo 'package classify'; echo
    for ((i = 0; i < n; i++)); do printf 'func f%d(x int) int {\n\tif x > %d {\n\t\treturn x - %d\n\t}\n\treturn %d\n}\n\n' $i $i $i $i; done
    echo 'func BigRun() int {'; echo '	s := 0'
    for ((i = 0; i < n; i += 2)); do printf '\ts += f%d(0)\n' $i; done
    echo '	return s'; echo '}' ;;
  js)
    echo '// Generated by gen-big.sh. Do not edit.'
    for ((i = 0; i < n; i++)); do printf 'function f%d(x) {\n  if (x > %d) return x - %d;\n  return %d;\n}\n' $i $i $i $i; done
    echo 'function bigRun() {'; echo '  let s = 0;'
    for ((i = 0; i < n; i += 2)); do printf '  s += f%d(0);\n' $i; done
    echo '  return s;'; echo '}'; echo 'module.exports = { bigRun };' ;;
  py)
    echo '# Generated by gen-big.sh. Do not edit.'
    for ((i = 0; i < n; i++)); do printf 'def f%d(x):\n    if x > %d:\n        return x - %d\n    return %d\n\n\n' $i $i $i $i; done
    echo 'def big_run():'; echo '    s = 0'
    for ((i = 0; i < n; i += 2)); do printf '    s += f%d(0)\n' $i; done
    echo '    return s' ;;
  java)
    echo '// Generated by gen-big.sh. Do not edit.'; echo 'package attra.sample;'; echo 'public final class Big {'
    for ((i = 0; i < n; i++)); do printf '    static int f%d(int x) {\n        if (x > %d) return x - %d;\n        return %d;\n    }\n' $i $i $i $i; done
    echo '    public static int run() {'; echo '        int s = 0;'
    for ((i = 0; i < n; i += 2)); do printf '        s += f%d(0);\n' $i; done
    echo '        return s;'; echo '    }'; echo '}' ;;
  cs)
    echo '// Generated by gen-big.sh. Do not edit.'; echo 'namespace Attra.Sample;'; echo 'public static class Big'; echo '{'
    for ((i = 0; i < n; i++)); do printf '    static int F%d(int x)\n    {\n        if (x > %d) return x - %d;\n        return %d;\n    }\n' $i $i $i $i; done
    echo '    public static int Run()'; echo '    {'; echo '        int s = 0;'
    for ((i = 0; i < n; i += 2)); do printf '        s += F%d(0);\n' $i; done
    echo '        return s;'; echo '    }'; echo '}' ;;
  php)
    echo '<?php'; echo '// Generated by gen-big.sh. Do not edit.'; echo 'namespace Attra\Sample;'; echo 'final class Big'; echo '{'
    for ((i = 0; i < n; i++)); do printf '    public static function f%d(int $x): int\n    {\n        if ($x > %d) {\n            return $x - %d;\n        }\n        return %d;\n    }\n' $i $i $i $i; done
    echo '    public static function run(): int'; echo '    {'; echo '        $s = 0;'
    for ((i = 0; i < n; i += 2)); do printf '        $s += self::f%d(0);\n' $i; done
    echo '        return $s;'; echo '    }'; echo '}' ;;
  rb)
    echo '# Generated by gen-big.sh. Do not edit.'; echo 'module Big'
    for ((i = 0; i < n; i++)); do printf '  def self.f%d(x)\n    return x - %d if x > %d\n    %d\n  end\n' $i $i $i $i; done
    echo '  def self.run'; echo '    s = 0'
    for ((i = 0; i < n; i += 2)); do printf '    s += f%d(0)\n' $i; done
    echo '    s'; echo '  end'; echo 'end' ;;
  rs)
    echo '// Generated by gen-big.sh. Do not edit.'
    for ((i = 0; i < n; i++)); do printf 'fn f%d(x: i64) -> i64 {\n    if x > %d {\n        return x - %d;\n    }\n    %d\n}\n' $i $i $i $i; done
    echo 'pub fn big_run() -> i64 {'; echo '    let mut s = 0;'
    for ((i = 0; i < n; i += 2)); do printf '    s += f%d(0);\n' $i; done
    echo '    s'; echo '}' ;;
  dart)
    echo '// Generated by gen-big.sh. Do not edit.'
    for ((i = 0; i < n; i++)); do printf 'int f%d(int x) {\n  if (x > %d) return x - %d;\n  return %d;\n}\n' $i $i $i $i; done
    echo 'int bigRun() {'; echo '  var s = 0;'
    for ((i = 0; i < n; i += 2)); do printf '  s += f%d(0);\n' $i; done
    echo '  return s;'; echo '}' ;;
  swift)
    echo '// Generated by gen-big.sh. Do not edit.'
    for ((i = 0; i < n; i++)); do printf 'func f%d(_ x: Int) -> Int {\n    if x > %d { return x - %d }\n    return %d\n}\n' $i $i $i $i; done
    echo 'public func bigRun() -> Int {'; echo '    var s = 0'
    for ((i = 0; i < n; i += 2)); do printf '    s += f%d(0)\n' $i; done
    echo '    return s'; echo '}' ;;
  *) echo "unknown language: $lang" >&2; exit 2 ;;
esac
